# paywall-1105 A: letter+before/after packaging (flags stay OFF).
from playwright.sync_api import sync_playwright
import sys, os, subprocess, time, re
HERE = os.path.dirname(os.path.abspath(__file__))
DEPLOY = os.path.normpath(os.path.join(HERE, ".."))
srv = subprocess.Popen([sys.executable, "-m", "http.server", "8989"], cwd=DEPLOY, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL); time.sleep(1)
fails = []
def ck(c, m):
    if not c: fails.append(m)
html = open(os.path.join(DEPLOY, "app", "index.html")).read()
land = open(os.path.join(DEPLOY, "index.html")).read()
ck(re.search(r"PAYWALL_ENABLED\s*=\s*false", html) and re.search(r"LICENSE_SERVER_ENABLED\s*=\s*false", html), "flags must stay false")
ck("USD 49/year; monthly is USD 9.99/month" in html and "end of the paid period" in html, "upFine not Legal string")
ck("Patterns, trends and movement insight" in html and "movement insight and MRS" not in html, "upL4 still markets MRS")
ck("save ~59%" not in html, "59% savings claim still present")
ck('${t("upTry")}: ${PLUS_PRICE.y} / year · ${PLUS_PRICE.ym}/mo' in html, "yearly button wording")
ck("FOUNDING, drops the first year to USD 39" in html, "cost FAQ missing FOUNDING Legal string")
ck("blur(12px)" in html, "teaser blur not >=12px")
ck('PLUS_PRICE={m:"$9.99",y:"$49",ym:"$4.08"}' in html or "PLUS_PRICE={m:\"$9.99\",y:\"$49\",ym:\"$4.08\"}" in html, "PLUS_PRICE changed")
ck("Is it working?" not in html, "in-app still says Is it working?")
ck('hwT:"Before and after"' in html, "hwT not renamed")
ck('upT:"Get your doctor letter"' in html, "upT not letter-led")
# upgrade list order
m = re.search(r'upL1:"([^"]+)".*?upL2:"([^"]+)".*?upL3:"([^"]+)".*?upL4:"([^"]+)".*?upL5:"([^"]+)"', html, re.S)
ck(bool(m), "upL* missing")
if m:
    ck(m.group(1).lower().startswith("print or save") and "letter" in m.group(1).lower(), "upL1 should be doctor letter: "+m.group(1))
    ck("before and after" in m.group(2).lower(), "upL2 should be before/after: "+m.group(2))
    ck(m.group(5).lower()=="csv export" or "csv" in m.group(5).lower(), "upL5 should be CSV")
ck("can't tell you whether a treatment works" in html or "can’t tell you whether a treatment works" in html, "Legal note missing in app")
ck("Started HRT or a supplement? See your before and after." in land, "landing before/after hero missing")
ck(land.find("Started HRT or a supplement?") < land.find("Sound familiar?"), "landing before/after not after hero")
ck("before-after.webp" in land, "landing missing before-after image")
ck(os.path.isfile(os.path.join(DEPLOY, "img", "before-after.webp")), "before-after.webp file missing")
ck("peri-v48" in open(os.path.join(DEPLOY, "app", "sw.js")).read().splitlines()[0], "cache not peri-v48")
with sync_playwright() as p:
    b = p.chromium.launch()
    pg = b.new_page(viewport={"width": 390, "height": 844}, reduced_motion="reduce")
    pg.on("dialog", lambda d: d.accept()); errs=[]
    pg.on("pageerror", lambda e: errs.append(str(e)))
    pg.goto("http://localhost:8989/app/"); pg.evaluate("localStorage.clear()"); pg.reload(); pg.wait_for_timeout(300)
    pg.evaluate("S.onb=true;S.instSeen=true;S.lang='en';S.t0=today();persist()"); pg.reload(); pg.wait_for_timeout(400)
    pg.evaluate("show('settings');$('demoBtn').click()"); pg.wait_for_timeout(1800)
    pg.evaluate("show('insights')"); pg.wait_for_timeout(300)
    ck(pg.evaluate("$('hwCard')&&$('hwCard').querySelector('h3').innerText")=="Before and after", "visible title not Before and after")
    ck(pg.evaluate("!!$('hwBox')&&$('hwBox').innerText.includes('Overall symptom load')"), "unlocked card should show numbers with flags off")
    # letter At a glance placement
    pg.evaluate("show('summary');sumMode='let';S.lr='3';persist();renderSummary()"); pg.wait_for_timeout(300)
    text = pg.evaluate("$('sumBody').innerText")
    ck("At a glance" in text and "4 weeks before" in text, "letter missing before/after line")
    ck(text.find("At a glance") < text.find("4 weeks before") < text.find("Symptoms over time"), "L_hw not inside At a glance before Symptoms")
    # locked teaser via hasAccess override (flags still false in source)
    pg.evaluate("hasAccess=function(){return false}; show('insights')"); pg.wait_for_timeout(400)
    box = pg.evaluate("$('hwBox')&&$('hwBox').innerText")
    ck(pg.evaluate("!!$('hwCard')&&getComputedStyle($('hwCard')).display!=='none'"), "hwCard hidden when locked")
    ck(box and "Unlock before and after + your doctor letter" in box and "••" in box, "locked teaser missing: "+str(box)[:200])
    ck(not re.search(r"\d+\.\d+", box or ""), "teaser leaked decimal averages")
    # upsell order
    pg.evaluate("openUp()"); pg.wait_for_timeout(200)
    up = pg.evaluate("$('shB').innerText")
    ck("Get your doctor letter" in up, "sheet title")
    ck(up.find("Print or save") < up.find("before and after") < up.find("CSV export"), "sheet feature order wrong")
    # today nudge
    pg.evaluate("$('sheet').classList.add('hide');hasAccess=function(){return true}; show('today')"); pg.wait_for_timeout(300)
    ck("Before and after" in pg.evaluate("$('v-today').innerText"), "today nudge missing")
    if errs: fails.append("page errors: "+", ".join(errs))
    # landing
    lp = b.new_page(viewport={"width": 390, "height": 844})
    lp.goto("http://localhost:8989/"); lp.wait_for_timeout(400)
    hs = lp.evaluate("[...document.querySelectorAll('main h2')].map(h=>h.innerText.trim())")
    ck(hs and hs[0].startswith("A little check-in"), "landing first h2 should be how-it-helps: "+str(hs[:3]))
    ck("Is it working?" not in lp.content(), "landing has Is it working?")
    b.close()
srv.terminate()
print("PASS" if not fails else "FAIL\n"+"\n".join(fails)); sys.exit(1 if fails else 0)
